using System.Globalization;
using System.Text;

namespace Garethp.ModsOfMistriaInstallerLib.Variants;

/// <summary>
/// Renders the plan as plain GML data for the in-game runtime. GML (not fiddle) because the
/// framework's code reads it directly, and because AIM compile-checks every staged GML file, so
/// a malformed registry fails the install's check instead of the game.
/// </summary>
public static class VariantRegistryWriter
{
    private const int MaxWarnings = 60;

    public static string Render(VariantSession session, string installerVersion, DateTimeOffset now)
    {
        var plan = session.Plan;
        var gml = new StringBuilder();
        gml.Append("// Generated by AIM for the Variants Framework. Rewritten on every install; do not edit.\n");
        gml.Append("// ").Append(plan.RuntimeFamilies.Count).Append(" switchable families, ")
            .Append(plan.InstallOnlyFamilies.Count).Append(" install-time choices.\n");
        gml.Append("function ").Append(VariantFramework.RegistryFunction).Append("() {\n");
        gml.Append("    return {\n");
        gml.Append("        schema: 1,\n");
        gml.Append("        installer: ").Append(Str(installerVersion)).Append(",\n");
        gml.Append("        generated: ").Append(Str(now.UtcDateTime.ToString("yyyy-MM-dd'T'HH:mm:ss'Z'", CultureInfo.InvariantCulture))).Append(",\n");

        gml.Append("        looks: [\n");
        foreach (var look in plan.Looks.Values.Where(l => l.IsVanilla || UsedLook(plan, l.Id)))
        {
            gml.Append("            { id: ").Append(Str(look.Id))
                .Append(", name: ").Append(Str(look.Name))
                .Append(", mod_id: ").Append(Str(look.ModId))
                .Append(", author: ").Append(Str(look.Author))
                .Append(" },\n");
        }
        gml.Append("        ],\n");

        gml.Append("        families: [\n");
        foreach (var family in plan.RuntimeFamilies) AppendFamily(gml, family, session);
        gml.Append("        ],\n");

        gml.Append("        install_only: [\n");
        foreach (var family in plan.InstallOnlyFamilies) AppendFamily(gml, family, session);
        gml.Append("        ],\n");

        gml.Append("        item_variants: [\n");
        foreach (var v in session.ItemVariants)
        {
            gml.Append("            { item: ").Append(Str(v.ItemId))
                .Append(", object: ").Append(Str(v.ObjectId))
                .Append(", base_item: ").Append(Str(v.BaseItem))
                .Append(", base_object: ").Append(Str(v.BaseObject))
                .Append(", look: ").Append(Str(v.LookId))
                .Append(", family: ").Append(Str(v.FamilyId))
                .Append(" },\n");
        }
        gml.Append("        ],\n");

        gml.Append("        retired_items: [\n");
        foreach (var v in session.RetiredItems)
        {
            gml.Append("            { item: ").Append(Str(v.ItemId))
                .Append(", object: ").Append(Str(v.ObjectId))
                .Append(", base_item: ").Append(Str(v.BaseItem))
                .Append(", base_object: ").Append(Str(v.BaseObject))
                .Append(" },\n");
        }
        gml.Append("        ],\n");

        gml.Append("        animal_variants: [\n");
        foreach (var v in session.AnimalVariants)
        {
            gml.Append("            { kind: ").Append(Str(v.Kind))
                .Append(", variant: ").Append(Str(v.VariantId))
                .Append(", base: ").Append(Str(v.BaseVariant))
                .Append(", look: ").Append(Str(v.LookId))
                .Append(", family: ").Append(Str(v.FamilyId))
                .Append(" },\n");
        }
        gml.Append("        ],\n");

        gml.Append("        warnings: [\n");
        foreach (var warning in plan.Warnings.Take(MaxWarnings))
            gml.Append("            ").Append(Str(warning)).Append(",\n");
        gml.Append("        ],\n");

        gml.Append("        stats: { families: ").Append(plan.RuntimeFamilies.Count)
            .Append(", install_only: ").Append(plan.InstallOnlyFamilies.Count)
            .Append(", look_sprites: ").Append(plan.LookSpriteCount)
            .Append(", original_copies: ").Append(plan.VanillaCopyCount)
            .Append(", variant_items: ").Append(session.ItemVariants.Count)
            .Append(", animal_variants: ").Append(session.AnimalVariants.Count)
            .Append(", warnings: ").Append(plan.Warnings.Count)
            .Append(" },\n");

        gml.Append("    };\n");
        gml.Append("}\n");
        return gml.ToString();
    }

    private static bool UsedLook(VariantPlan plan, string lookId) =>
        plan.RuntimeFamilies.Concat(plan.InstallOnlyFamilies).Any(f => f.Looks.Any(l => l.Look.Id == lookId));

    private static void AppendFamily(StringBuilder gml, PlannedFamily planned, VariantSession session)
    {
        var family = planned.Family;
        gml.Append("            {\n");
        gml.Append("                id: ").Append(Str(family.Id)).Append(",\n");
        gml.Append("                kind: ").Append(Str(KindName(family.Kind))).Append(",\n");
        gml.Append("                key: ").Append(Str(family.Key)).Append(",\n");
        gml.Append("                name: ").Append(Str(family.DisplayName)).Append(",\n");
        gml.Append("                items: [").Append(string.Join(", ", family.ItemIds.Select(Str))).Append("],\n");
        gml.Append("                icon: ").Append(Str(family.IconSprite ?? "")).Append(",\n");
        gml.Append("                preview: ").Append(Str(family.PreviewSprite ?? "")).Append(",\n");
        gml.Append("                default_look: ").Append(Str(planned.InstallDefault)).Append(",\n");
        gml.Append("                looks: [\n");
        foreach (var look in planned.Looks)
        {
            var variantItem = session.ItemVariants.FirstOrDefault(v => v.FamilyId == family.Id && v.LookId == look.Look.Id);
            gml.Append("                    { id: ").Append(Str(look.Look.Id))
                .Append(", preview: ").Append(Str(look.Resolve(look.PreviewSprite ?? family.PreviewSprite ?? "")))
                .Append(", thumb: ").Append(Str(look.Thumbnail ?? ""))
                .Append(", changed: ").Append(look.Changed.Count)
                .Append(", item: ").Append(Str(variantItem?.ItemId ?? ""))
                .Append(", map: [");
            var first = true;
            foreach (var (from, to) in look.Map)
            {
                if (from == to) continue;
                if (!first) gml.Append(", ");
                gml.Append(Str(from)).Append(", ").Append(Str(to));
                first = false;
            }
            gml.Append("] },\n");
        }
        gml.Append("                ],\n");
        gml.Append("            },\n");
    }

    public static string KindName(FamilyKind kind) => kind switch
    {
        FamilyKind.Furniture => "furniture",
        FamilyKind.Animal => "animal",
        FamilyKind.Pet => "pet",
        FamilyKind.Building => "building",
        FamilyKind.WorldObject => "world",
        FamilyKind.Item => "item",
        FamilyKind.InstallOnly => "install_only",
        _ => "other",
    };

    /// <summary>A GML string literal: quotes and backslashes escaped, control characters dropped.</summary>
    public static string Str(string? value)
    {
        var builder = new StringBuilder((value?.Length ?? 0) + 2);
        builder.Append('"');
        foreach (var c in value ?? "")
        {
            switch (c)
            {
                case '"': builder.Append("\\\""); break;
                case '\\': builder.Append("\\\\"); break;
                default:
                    if (!char.IsControl(c)) builder.Append(c);
                    break;
            }
        }

        builder.Append('"');
        return builder.ToString();
    }
}
